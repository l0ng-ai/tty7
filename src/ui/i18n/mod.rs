/// The source control strings that are translated but not yet displayed.
///
/// They all ship in one go so the three language files are edited once for the
/// whole feature instead of once per step, and so the wording can be reviewed
/// as a set rather than a string at a time. Naming them here is what keeps
/// `dead_code` reporting on the rest of the enum: without it every unused key
/// is folded into one warning and a genuinely stale key hides in the crowd.
///
/// **Delete a key from this list as soon as something renders it.**
#[allow(dead_code)]
const SCM_KEYS_AWAITING_A_CALLER: &[L10nKey] = &[
    L10nKey::ScmCheckoutBranch,
    L10nKey::ScmCommitDetailTitle,
    L10nKey::ScmCommitStaged,
    L10nKey::ScmResetToCommit,
    L10nKey::ScmSearchBranches,
    L10nKey::ScmStashAndSwitch,
];

pub fn set_locale(gui_language: &str) {
    let index = SUPPORTED_LANGUAGES
        .iter()
        .position(|lang| lang.code == gui_language)
        .unwrap_or(0) as u8;
    #[cfg(test)]
    TEST_LOCALE.with(|slot| slot.set(Some(index)));
    #[cfg(not(test))]
    CURRENT.store(index, Ordering::Relaxed);
}

pub fn t(key: L10nKey) -> &'static str {
    translate(current_locale_index(), key)
}

pub fn t_fmt(key: L10nKey, args: &[(&str, &str)]) -> String {
    apply_template(t(key), args, None)
}

/// The same key as every *other* locale words it.
///
/// Fingers learn a command's name once. Someone running the UI in Chinese who
/// picked the habit up in English still types `theme`, and until this existed
/// the palette answered "no matching commands" — the label it was matching
/// against was the only one that existed. Callers keep these as hidden search
/// aliases; nothing renders them, so the wording on screen never changes.
pub fn alias_translations(key: L10nKey) -> Vec<&'static str> {
    let shown = t(key);
    let mut out = Vec::with_capacity(SUPPORTED_LANGUAGES.len() - 1);
    for idx in 0..SUPPORTED_LANGUAGES.len() {
        let text = translate(idx, key);
        if text != shown && !out.contains(&text) {
            out.push(text);
        }
    }
    out
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PluralCategory {
    Zero,
    One,
    Other,
}

impl PluralCategory {
    pub fn from_count(n: usize) -> Self {
        match n {
            0 => Self::Zero,
            1 => Self::One,
            _ => Self::Other,
        }
    }

    pub fn as_str(self) -> &'static str {
        match self {
            Self::Zero => "zero",
            Self::One => "one",
            Self::Other => "other",
        }
    }
}

/// Select a plural-aware translation and fill placeholders.
/// The template may use `{count}`; it is always substituted first.
pub fn t_plural(key: L10nKey, count: usize, args: &[(&str, &str)]) -> String {
    let branch = PluralCategory::from_count(count).as_str();
    apply_template(
        translate_variant(current_locale_index(), key, branch),
        args,
        Some(count),
    )
}

/// Select a named branch of a translation and fill placeholders.
pub fn t_select(key: L10nKey, branch: &'static str, args: &[(&str, &str)]) -> String {
    apply_template(
        translate_variant(current_locale_index(), key, branch),
        args,
        None,
    )
}

fn apply_template(template: &'static str, args: &[(&str, &str)], count: Option<usize>) -> String {
    let mut text = template.to_string();
    if let Some(n) = count {
        text = text.replace("{count}", &n.to_string());
    }
    for (name, value) in args {
        text = text.replace(&format!("{{{name}}}"), value);
    }
    text
}

fn current_locale_index() -> usize {
    #[cfg(test)]
    if let Some(idx) = TEST_LOCALE.with(|slot| slot.get()) {
        return idx as usize;
    }
    CURRENT.load(Ordering::Relaxed) as usize
}

fn translate(locale_idx: usize, key: L10nKey) -> &'static str {
    if let Some(lang) = SUPPORTED_LANGUAGES.get(locale_idx) {
        if let Some(text) = (lang.translate_fn)(key) {
            return text;
        }
    }
    translate_en(key)
}

fn translate_variant(locale_idx: usize, key: L10nKey, branch: &'static str) -> &'static str {
    if let Some(lang) = SUPPORTED_LANGUAGES.get(locale_idx) {
        if let Some(text) = (lang.translate_variant_fn)(key, branch) {
            return text;
        }
    }
    translate_variant_en(key, branch).unwrap_or_else(|| translate(locale_idx, key))
}

