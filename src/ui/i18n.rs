pub fn set_locale(gui_language: &str) {
    let locale = if gui_language == "auto" {
        detect_system_language()
    } else if matches!(
        gui_language,
        "zh-CN" | "zh-Hans" | "zh_CN" | "zh_Hans" | "zh"
    ) {
        ZH_HANS
    } else {
        EN
    };
    CURRENT.store(locale, Ordering::Relaxed);
}

pub fn t(key: L10nKey) -> &'static str {
    translate(current_locale(), key)
}

pub fn is_zh_hans() -> bool {
    current_locale() == Locale::ZhHans
}

pub fn t_fmt(key: L10nKey, args: &[(&str, &str)]) -> String {
    apply_template(t(key), args, None)
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PluralCategory {
    Zero,
    One,
    Other,
}

impl PluralCategory {
    pub fn from_count(n: usize) -> Self {
        match n {
            0 => Self::Zero,
            1 => Self::One,
            _ => Self::Other,
        }
    }

    pub fn as_str(self) -> &'static str {
        match self {
            Self::Zero => "zero",
            Self::One => "one",
            Self::Other => "other",
        }
    }
}

/// Select a plural-aware translation and fill placeholders.
/// The template may use `{count}`; it is always substituted first.
pub fn t_plural(key: L10nKey, count: usize, args: &[(&str, &str)]) -> String {
    let branch = PluralCategory::from_count(count).as_str();
    apply_template(translate_variant(current_locale(), key, branch), args, Some(count))
}

/// Select a named branch of a translation and fill placeholders.
pub fn t_select(key: L10nKey, branch: &'static str, args: &[(&str, &str)]) -> String {
    apply_template(translate_variant(current_locale(), key, branch), args, None)
}

fn apply_template(template: &'static str, args: &[(&str, &str)], count: Option<usize>) -> String {
    let mut text = template.to_string();
    if let Some(n) = count {
        text = text.replace("{count}", &n.to_string());
    }
    for (name, value) in args {
        text = text.replace(&format!("{{{name}}}"), value);
    }
    text
}

fn current_locale() -> Locale {
    if CURRENT.load(Ordering::Relaxed) == ZH_HANS {
        Locale::ZhHans
    } else {
        Locale::En
    }
}

fn detect_system_language() -> u8 {
    for var in ["LC_ALL", "LC_MESSAGES", "LANG"] {
        if let Ok(value) = std::env::var(var) {
            let value = value.to_ascii_lowercase();
            if value.starts_with("zh_") || value.starts_with("zh-") {
                return ZH_HANS;
            }
        }
    }
    EN
}

